    existing_names = {p["name"].lower() for p in places}

    counter = 0
    for zone_name, z_lat, z_lng, pincode in PUNE_ZONES:
        for cat, subcat, facility, tags, price, base_rate in FACILITIES_TEMPLATES:
            brand = BRAND_PREFIXES[counter % len(BRAND_PREFIXES)]
            counter += 1
            name = f"{brand} {facility} ({zone_name})"
            if name.lower() in existing_names:
                continue
            existing_names.add(name.lower())

            lat_diff = ((counter % 9) - 4) * 0.0016
            lng_diff = (((counter * 2) % 9) - 4) * 0.0016
            p_lat = round(z_lat + lat_diff, 4)
            p_lng = round(z_lng + lng_diff, 4)

            rating = round(min(4.9, max(4.0, base_rate + ((counter % 4) - 1) * 0.1)), 1)
            rcount = 150 + (counter * 73) % 4800

            clean = round(78.0 + (counter % 20), 1)
            safe = round(80.0 + ((counter * 3) % 18), 1)
            afford = round(60.0 + ((counter * 4) % 35), 1)
            access = round(75.0 + ((counter * 2) % 22), 1)
